export const GLYPH_W = 5;
export const GLYPH_H = 7;
const cache = new Map();

export function textWidth(text, scale = 1) {
  return text.length * (GLYPH_W + 1) * scale - scale;
}

/**
 * Draw `text` with its top-left corner at (x, y). Mixed case is kept (there is
 * a small lowercase set); pass upper=true to force capitals.
 * Rendered strings are cached on offscreen canvases keyed by text/colour/scale.
 */
export function drawText(ctx, text, x, y, color = '#fff', scale = 1, upper = false) {
  text = String(text);
  if (upper) text = text.toUpperCase();
  if (!text) return 0;
  const key = `${scale}|${color}|${text}`;
  let c = cache.get(key);
  if (!c) {
    const w = textWidth(text, scale);
    c = document.createElement('canvas');
    c.width = Math.max(1, w);
    c.height = GLYPH_H * scale;
    const g = c.getContext('2d');
    g.fillStyle = color;
    let cx = 0;
    for (const ch of text) {
      const rows = G[ch] || G[ch.toUpperCase()] || G['?'];
      for (let r = 0; r < GLYPH_H; r++) {
        const row = rows[r];
        for (let k = 0; k < GLYPH_W; k++) {
          if (row[k] === '#') g.fillRect(cx + k * scale, r * scale, scale, scale);
        }
      }
      cx += (GLYPH_W + 1) * scale;
    }
    if (cache.size > 400) cache.delete(cache.keys().next().value);
    cache.set(key, c);
  }
  ctx.drawImage(c, Math.round(x), Math.round(y));
  return c.width;
}
